/**
 * Path Painter level set — 60 handcrafted roller-paint puzzles in six chapters of ten.
 *
 * The brush rolls in the swiped direction until a wall, a shut gate, or a used
 * crumble tile stops it (turn pads `> < ^ v` bend the roll on the way),
 * painting every tile it crosses. Win = every paintable tile covered. No move
 * limit; stars come from par (= BFS-optimal strokes). Only L53 and L58 carry a
 * (generous) clock. Every board is a planning puzzle: real junctions, loops, rooms
 * and stubs where WHERE the brush stops decides what you can paint next. See
 * docs/LEVELS.md for the chapter plan and every level's role and "aha";
 * src/game/sim.ts describe() prints the same intent for review.
 *
 * Chapter N holds levels 10(N-1)+1 … 10N (one gallery piece per level). Each
 * level stores the solver's BFS-optimal cover path in `solution` (= parMoves) —
 * scripts/validate.ts replays it through the REAL engine to prove the board
 * completable. `botBudget` (the playtest bots' swipe budget, never shown in the
 * UI) is set by scripts/tune-levels.ts to the pacing curve. No two start states
 * are identical (the playtest duplicate check enforces it).
 */
